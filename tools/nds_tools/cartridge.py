"""Original-image preparation shared by DS cartridge consumers.

Title code owns identity, executable-address policy and coverage. This module
owns decompression, validated overlay extraction and compiler config encoding.
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path

def sha1(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()

def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)

def write_seed_config(
    path: Path,
    *,
    name: str,
    program_id: str,
    load_address: int,
    entry_pc: int,
    binary: bytes,
    coverage_entries: list[dict[str, object]],
    generated_by: str = "ndsrecomp preparation",
) -> None:
    lines = [
                f"# AUTO-GENERATED by {generated_by}; do not commit.",
                "[program]",
                f"name = {toml_string(name)}",
                f"id = {toml_string(program_id)}",
                f"load_address = 0x{load_address:08x}",
                f"size = 0x{len(binary):08x}",
                f"entry_pc = 0x{entry_pc:08x}",
                "authoritative_entry_points = false",
                "",
                "[identity]",
                f"sha1 = {toml_string(sha1(binary))}",
                "",
                "[[entry_point]]",
                f"addr = 0x{entry_pc:08x}",
                'mode = "arm"',
                'name = "entry"',
                'kind = "rom_header"',
                "",
            ]
    for entry in coverage_entries:
        addr = int(str(entry["addr"]), 0)
        mode = str(entry["mode"])
        lines.extend(
            [
                "[[entry_point]]",
                f"addr = 0x{addr:08x}",
                f"mode = {toml_string(mode)}",
                f"name = {toml_string(f'coverage_{addr:08x}')}",
                'kind = "tier3_coverage"',
                "",
            ]
        )
    path.write_text(
        "\n".join(lines),
        encoding="utf-8",
        newline="\n",
    )

def write_overlay_config(
    path: Path,
    *,
    title: str,
    program_id: str,
    overlay_id: int,
    load_address: int,
    binary: bytes,
    bss_size: int,
    static_init_start: int,
    static_init_end: int,
    coverage_entries: list[dict[str, object]] = (),
    generated_by: str = "ndsrecomp preparation",
) -> None:
    """Emit a recompiler seed config for one ARM9 overlay unit.

    An overlay has no ROM-header entry point: the guest's own loader copies
    the image to `load_address` and enters it through pointers the main image
    holds, so no root is seeded here — real entry points arrive from Tier-3
    coverage recorded while this exact body was resident (the
    MarioKartDSRecomp probe/build tools are the reference consumers).
    The [overlay] table carries the facts a content-validated dispatch row
    needs: the exact image identity and the static-init span, the one region
    the guest legitimately mutates after load.
    """
    lines = [
        f"# AUTO-GENERATED by {generated_by}; do not commit.",
        "[program]",
        f"name = {toml_string(f'{title} ARM9 overlay {overlay_id}')}",
        f"id = {toml_string(f'{program_id}_ov{overlay_id:03d}')}",
        f"load_address = 0x{load_address:08x}",
        f"size = 0x{len(binary):08x}",
        f"entry_pc = 0x{load_address:08x}",
        "authoritative_entry_points = false",
        "",
        "[identity]",
        f"sha1 = {toml_string(sha1(binary))}",
        "",
        "[overlay]",
        f"id = {overlay_id}",
        f"bss_size = 0x{bss_size:08x}",
        f"static_init_start = 0x{static_init_start:08x}",
        f"static_init_end = 0x{static_init_end:08x}",
        "",
    ]
    for entry in coverage_entries:
        addr = int(str(entry["addr"]), 0)
        mode = str(entry["mode"])
        lines.extend(
            [
                "[[entry_point]]",
                f"addr = 0x{addr:08x}",
                f"mode = {toml_string(mode)}",
                f"name = {toml_string(f'overlay_{overlay_id:03d}_{mode}_{addr:08x}')}",
                'kind = "tier3_overlay_coverage"',
                "",
            ]
        )
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def arm_images(rom):
    import ndspy.codeCompression as compression
    compressed = bytes(rom.arm9)
    arm9 = compression.decompress(compressed)
    return (arm9 if len(arm9) >= len(compressed) else compressed), bytes(rom.arm7)


def extract_overlay(overlay_id, overlay, output):
    """Validate before writing; return exact bytes and the portable manifest row."""
    data = bytes(overlay.data)
    if len(data) != int(overlay.ramSize):
        raise SystemExit(f"overlay {overlay_id} length mismatch: {len(data)} != {overlay.ramSize}")
    address = int(overlay.ramAddress)
    if not 0 <= address <= 0xffffffff or address + len(data) + int(overlay.bssSize) > 0x100000000:
        raise SystemExit(f"overlay {overlay_id} address range overflows")
    filename = f"arm9_overlay_{overlay_id:03d}.bin"
    record = dict(id=overlay_id, file=filename, file_id=int(overlay.fileID),
                  load_address=f"0x{address:08x}", size=int(overlay.ramSize),
                  bss_size=int(overlay.bssSize), static_init_start=f"0x{int(overlay.staticInitStart):08x}",
                  static_init_end=f"0x{int(overlay.staticInitEnd):08x}",
                  compressed_in_rom=bool(overlay.compressed), compressed_size=int(overlay.compressedSize),
                  sha1=sha1(data))
    (output / filename).write_bytes(data)
    return data, record
